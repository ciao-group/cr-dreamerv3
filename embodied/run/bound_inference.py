"""Inference of human bounds from Atari-HEAD and human-likeness evaluation.

infer_bounds: the agent is trained for a prior over bounds theta (observation
  `bounds`). Human trials are replayed with teacher forcing and the
  log-likelihood of the human's actions, gaze and pauses is maximised over
  theta with the cross-entropy method. Network weights are never fitted to
  human data.
bound_recovery: identifiability check. Trajectories are generated by the agent
  at known theta and theta is inferred back from them.
eval_human_likeness: closed-loop rollouts at a fixed theta, compared with
  human trials using distributional gaze statistics, saliency and scores.
"""

import collections
import json
import os

import elements
import numpy as np

from embodied.core import atari_head
from embodied.core import bounds as bounds_lib
from embodied.core import cr_replay
from embodied.core import scanpath_metrics as sm

HEADS = ('action', 'gaze_position', 'pause')


def infer_bounds(make_agent, make_env, make_logger, config):
  cfg = config.inference
  env = make_env(0)
  agent = _load_agent(make_agent, config)
  logger = make_logger()
  names = _bound_names(env)
  act_keys = _act_keys(agent)
  trials = _select_trials(cfg)
  print(f'Inferring {names} from {len(trials)} trials')
  sources = {
      trial.name: _human_source(trial, env, cfg, 'pause' in act_keys)
      for trial in trials}
  result = run_inference(agent, env, names, sources, cfg, logger)
  subjects = collections.defaultdict(list)
  for i, trial in enumerate(trials):
    subjects[trial.subject].append(i)
  result['subjects'] = {
      s: _best(result, idx) for s, idx in subjects.items()}
  result['trials'] = {
      t.name: _best(result, [i]) for i, t in enumerate(trials)}
  result['replay'] = replay_comparison(
      agent, env, names, sources, result['best']['values'], cfg)
  for key, value in result['replay'].items():
    if isinstance(value, float):
      logger.scalar(f'replay/{key}', value)
  logger.write()
  _save(config, 'inference.json', result)
  logger.close()
  return result


def bound_recovery(make_agent, make_env, make_logger, config):
  cfg = config.inference
  env = make_env(0)
  agent = _load_agent(make_agent, config)
  logger = make_logger()
  names = _bound_names(env)
  # Separate seed streams for the true thetas and the search candidates.
  theta_seed, search_seed = np.random.SeedSequence(cfg.seed).spawn(2)
  rng = np.random.default_rng(theta_seed)
  truth, estimate = [], []
  for k in range(cfg.recovery_thetas):
    u = rng.uniform(size=len(names))
    theta = bounds_lib.from_vector(names, u)
    env.bounds.freeze(**theta)
    record = rollout(agent, env, cfg.recovery_steps, record=True)['steps']
    result = run_inference(
        agent, env, names, {f'theta{k}': lambda r=record: iter(r)}, cfg,
        seed=search_seed.spawn(1)[0])
    truth.append(u)
    estimate.append(result['best']['normalized'])
    print(f'Recovery {k}: true {np.round(u, 2)} '
          f'inferred {np.round(estimate[-1], 2)}')
  truth, estimate = np.array(truth), np.array(estimate)
  out = {'names': list(names), 'true': truth.tolist(),
         'inferred': estimate.tolist(), 'correlation': {}, 'mae': {}}
  for i, name in enumerate(names):
    r = np.corrcoef(truth[:, i], estimate[:, i])[0, 1] if len(truth) > 2 else np.nan
    out['correlation'][name] = float(r)
    out['mae'][name] = float(np.abs(truth[:, i] - estimate[:, i]).mean())
    logger.scalar(f'recovery/corr_{name}', float(r))
    logger.scalar(f'recovery/mae_{name}', out['mae'][name])
  logger.write()
  _save(config, 'recovery.json', out)
  logger.close()
  return out


def eval_human_likeness(make_agent, make_env, make_logger, config):
  cfg = config.inference
  env = make_env(0)
  agent = _load_agent(make_agent, config)
  logger = make_logger()
  theta = {}
  if cfg.theta_file:
    with open(cfg.theta_file) as f:
      inferred = json.load(f)
    theta = (
        inferred['subjects'][cfg.subject]['values'] if cfg.subject
        else inferred['best']['values'])
  env.bounds.freeze(**theta)
  print('Evaluating at theta:', env.bounds.current)
  log = rollout(agent, env, cfg.eval_steps)

  agent_fix, agent_pauses = [], []
  rng = np.random.default_rng(cfg.seed)
  agent_jittered = []
  for ep in _split_episodes(log):
    ms = 1000 * np.asarray(ep['step_time'])
    agent_fix.append(cr_replay.fixations_from_cells(ep['gaze'], ms, env))
    agent_jittered.append(
        cr_replay.fixations_from_cells(ep['gaze'], ms, env, rng))
    agent_pauses += _pause_durations(ep['paused'], ms)
  agent_fix = np.concatenate(agent_fix)

  human_fix, human_raw_fix, human_pauses, human_scores = [], [], [], []
  for trial in _select_trials(cfg):
    fix = trial.fixations()
    human_raw_fix.append(fix)
    human_fix.append(cr_replay.quantize_fixations(fix, env))
    human_pauses += list(atari_head.pause_durations(trial))
    human_scores.append(trial.score / (trial.durations.sum() / 60000))
  human_fix = np.concatenate(human_fix)
  human_raw_fix = np.concatenate(human_raw_fix)

  grid = tuple(env.vision_square_count)
  screen = (env.W, env.H)
  pause_bins = np.concatenate([np.linspace(0, 2000, 21), [np.inf]])
  report = sm.distributional_report(
      sm.gaze_statistics(agent_fix, grid, screen),
      sm.gaze_statistics(human_fix, grid, screen),
      extra={'pause_duration': (agent_pauses, human_pauses, pause_bins)}
      if agent_pauses and human_pauses else None)
  report['human_likeness'] = sm.human_likeness_score(report)
  saliency = sm.saliency_report(
      np.concatenate(agent_jittered)[:, :2], human_raw_fix[:, :2],
      screen=screen)
  report.update({f'saliency_{k}': v for k, v in saliency.items()})
  minutes = float(np.sum(log['step_time']) / 60)
  report['score_per_minute'] = float(np.sum(log['game_score']) / max(minutes, 1e-9))
  report['human_score_per_minute'] = float(np.mean(human_scores))
  report['pause_rate'] = float(np.mean(log['paused']))
  report['agent_fixations'] = len(agent_fix)
  report['human_fixations'] = len(human_fix)
  report['theta'] = dict(env.bounds.current)
  for key, value in report.items():
    if isinstance(value, (int, float)) and np.isfinite(value):
      logger.scalar(f'human_likeness/{key}', value)
  logger.write()
  _save(config, 'human_likeness.json', report)
  logger.close()
  return report


def run_inference(agent, env, names, sources, cfg, logger=None, seed=None):
  """Cross-entropy search over normalised theta in [0, 1]^d.

  `sources` maps a name to a callable returning an iterator of ReplaySteps.
  Returns all evaluated candidates with their per-source log-likelihoods.
  """
  rng = np.random.default_rng(cfg.seed if seed is None else seed)
  d = len(names)
  units, logliks, details = [], [], []
  mean, std = np.full(d, 0.5), np.full(d, 0.5)
  for r in range(cfg.rounds):
    if r == 0:
      u = rng.uniform(size=(cfg.candidates, d))
    else:
      u = np.clip(rng.normal(mean, std, (cfg.candidates, d)), 0, 1)
    candidates = [bounds_lib.from_vector(names, row) for row in u]
    per_source = {
        name: score_source(agent, env, names, fn(), candidates)
        for name, fn in sources.items()}
    units.append(u)
    logliks.append(np.stack(
        [s['loglik'] for s in per_source.values()], 1))
    details.append(per_source)
    all_u = np.concatenate(units)
    total = np.concatenate(logliks).sum(1)
    n_elite = max(2, int(cfg.elite * len(total)))
    elite = all_u[np.argsort(total)[-n_elite:]]
    mean, std = elite.mean(0), elite.std(0) + 1e-3
    best = all_u[np.argmax(total)]
    print(f'Round {r}: best loglik {total.max():.1f} '
          f'theta {bounds_lib.from_vector(names, best)}')
    if logger:
      logger.scalar('inference/best_loglik', float(total.max()))
      for i, name in enumerate(names):
        logger.scalar(f'inference/{name}', bounds_lib.denormalize_value(
            name, best[i]))
        logger.scalar(f'inference/{name}_elite_std', float(std[i]))
      logger.write()
  result = {
      'names': list(names),
      'sources': list(sources),
      'normalized': np.concatenate(units).tolist(),
      'loglik': np.concatenate(logliks).tolist(),
      'elite_std': dict(zip(names, std.tolist())),
      'heads': _head_summary(details),
  }
  result['best'] = _best(result, list(range(len(sources))))
  return result


def score_source(agent, env, names, steps, candidates):
  """Teacher-forced log-likelihood of one trajectory for each candidate."""
  n = len(candidates)
  act_keys = _act_keys(agent)
  carry = agent.init_policy(n)
  totals = {k: np.zeros(n) for k in act_keys}
  counts = {k: 0 for k in act_keys}
  top1 = np.zeros(n)
  for step in steps:
    obs = cr_replay.batch_obs(step, env, candidates, names)
    act = cr_replay.batch_act(step, act_keys, n)
    carry, out = agent.score(carry, obs, act)
    masks = cr_replay.step_masks(step, act_keys)
    for key in act_keys:
      if masks[key]:
        totals[key] += out[f'logp/{key}']
        counts[key] += 1
    if masks['gaze_position']:
      top1 += out['logps/gaze_position'].argmax(-1) == step.gaze
  loglik = sum(totals.values())
  return {
      'loglik': loglik,
      'per_head': {k: (totals[k] / max(counts[k], 1)).tolist() for k in act_keys},
      'counts': counts,
      'gaze_top1': (top1 / max(counts['gaze_position'], 1)).tolist(),
  }


def replay_comparison(agent, env, names, sources, theta, cfg):
  """Teacher-forced replay at the inferred and at the default theta: mean
  NLL per head, gaze accuracy and paired scanpath metrics of the agent's
  most likely gaze against the human's next gaze."""
  defaults = {k: bounds_lib.SPECS[k].default for k in names}
  candidates = [dict(theta), defaults]
  act_keys = _act_keys(agent)
  grid = tuple(env.vision_square_count)
  out = {}
  sums = collections.defaultdict(lambda: np.zeros(2))
  counts = collections.Counter()
  paired = collections.defaultdict(list)
  for fn in sources.values():
    carry = agent.init_policy(2)
    model_cells, human_cells = [[], []], []
    for step in fn():
      obs = cr_replay.batch_obs(step, env, candidates, names)
      act = cr_replay.batch_act(step, act_keys, 2)
      carry, res = agent.score(carry, obs, act)
      masks = cr_replay.step_masks(step, act_keys)
      for key in act_keys:
        if masks[key]:
          sums[key] += -res[f'logp/{key}']
          counts[key] += 1
      if masks['gaze_position']:
        pred = res['logps/gaze_position'].argmax(-1)
        sums['gaze_top1'] += pred == step.gaze
        counts['gaze_top1'] += 1
        for i in range(2):
          model_cells[i].append(int(pred[i]))
        human_cells.append(step.gaze)
    for i, tag in enumerate(('inferred', 'default')):
      if len(human_cells) > 1:
        a = sm.collapse_repeats(model_cells[i])
        b = sm.collapse_repeats(human_cells)
        paired[f'{tag}_levenshtein'].append(sm.normalized_levenshtein(a, b))
        paired[f'{tag}_scanmatch'].append(sm.scanmatch(a, b, grid))
  for key, value in sums.items():
    name = key if key == 'gaze_top1' else f'nll_{key}'
    out[f'inferred_{name}'] = float(value[0] / max(counts[key], 1))
    out[f'default_{name}'] = float(value[1] / max(counts[key], 1))
  for key, values in paired.items():
    out[key] = float(np.mean(values))
  return out


def rollout(agent, env, n_steps, record=False):
  """Closed-loop rollout of the agent in the env. Returns per-step logs and,
  with `record`, ReplaySteps that can be scored like a human trial."""
  carry = agent.init_policy(1)
  act = {k: np.zeros((), v.dtype) for k, v in env.act_space.items()}
  act['reset'] = True
  obs = env.step(act)
  log = collections.defaultdict(list)
  steps = []
  for _ in range(n_steps):
    agent_obs = {k: np.asarray(v)[None] for k, v in obs.items()
                 if not k.startswith('log/')}
    carry, acts, _ = agent.policy(carry, agent_obs, mode='eval')
    act = {k: v[0] for k, v in acts.items()}
    act['reset'] = False
    if record:
      steps.append(cr_replay.ReplayStep(
          frames=[b.copy() for b in env.raw_buffers],
          fovea=int(env.prev_gaze_position),
          action=-1 if act.get('pause', 0) else int(act['action']),
          gaze=int(act['gaze_position']),
          pause=int(act.get('pause', 0)),
          reward=float(obs['reward']),
          is_first=bool(obs['is_first']),
          duration=1000 * float(obs['log/step_time'])))
    obs = env.step(act)
    log['is_first'].append(bool(obs['is_first']))
    log['gaze'].append(int(obs['log/gaze_position']))
    log['paused'].append(bool(obs['log/paused']))
    log['step_time'].append(float(obs['log/step_time']))
    log['game_score'].append(float(obs['log/game_score']))
    log['avatar_distance'].append(
        float(obs['log/avatar_distance_vision_square']))
  log = {k: np.array(v) for k, v in log.items()}
  log['steps'] = steps
  return log


def _split_episodes(log):
  starts = list(np.nonzero(log['is_first'])[0]) + [len(log['is_first'])]
  if starts[0] != 0:
    starts = [0] + starts
  for lo, hi in zip(starts[:-1], starts[1:]):
    # The first step of an episode is the reset observation.
    lo = lo + 1 if log['is_first'][lo] else lo
    if hi - lo > 1:
      yield {k: log[k][lo:hi] for k in ('gaze', 'paused', 'step_time')}


def _pause_durations(paused, ms):
  """Total duration of each run of consecutive pause steps."""
  out, current = [], 0.0
  for p, t in zip(paused, ms):
    if p:
      current += t
    elif current:
      out.append(current)
      current = 0.0
  return out


def _best(result, source_idx):
  ll = np.asarray(result['loglik'])[:, source_idx].sum(1)
  u = np.asarray(result['normalized'])[int(np.argmax(ll))]
  return {
      'loglik': float(ll.max()),
      'normalized': u.tolist(),
      'values': bounds_lib.from_vector(result['names'], u),
  }


def _head_summary(details):
  """Mean per-step NLL per head of the best candidate of the last round."""
  last = details[-1]
  total = sum(np.asarray(s['loglik']) for s in last.values())
  i = int(np.argmax(total))
  heads = collections.defaultdict(list)
  for s in last.values():
    for key, values in s['per_head'].items():
      heads[f'nll_{key}'].append(-values[i])
    heads['gaze_top1'].append(s['gaze_top1'][i])
  return {k: float(np.mean(v)) for k, v in heads.items()}


def _load_agent(make_agent, config):
  assert config.run.from_checkpoint, 'Set --run.from_checkpoint'
  agent = make_agent()
  cp = elements.Checkpoint()
  cp.agent = agent
  cp.load(config.run.from_checkpoint, keys=['agent'])
  return agent


def _bound_names(env):
  names = env.bounds.names
  assert names, (
      'The agent must be trained with sampled bounds, '
      'e.g. --env.cr-atari.bounds_sample all')
  return names


def _act_keys(agent):
  return [k for k in HEADS if k in agent.act_space]


def _select_trials(cfg):
  names = atari_head.list_trials(cfg.data)
  if cfg.trials:
    wanted = [t.strip() for t in cfg.trials.split(',')]
    names = [n for n in names if any(n.startswith(w) for w in wanted)]
  elif cfg.split != 'all':
    train, test = atari_head.split_trials(names)
    names = {'train': train, 'test': test}[cfg.split]
  if cfg.subject:
    names = [n for n in names if atari_head.subject_of(n) == cfg.subject]
  return [atari_head.load_trial(cfg.data, n) for n in names]


def _human_source(trial, env, cfg, split_pauses):
  return lambda: cr_replay.human_steps(
      trial, env, cfg.max_steps, split_pauses=split_pauses)


def _save(config, filename, data):
  path = os.path.join(str(config.logdir), filename)
  with open(path, 'w') as f:
    json.dump(_jsonable(data), f, indent=2)
  print('Saved', path)


def _jsonable(x):
  if isinstance(x, dict):
    return {str(k): _jsonable(v) for k, v in x.items()}
  if isinstance(x, (list, tuple)):
    return [_jsonable(v) for v in x]
  if isinstance(x, np.ndarray):
    return x.tolist()
  if isinstance(x, (np.floating, np.integer)):
    return x.item()
  return x
